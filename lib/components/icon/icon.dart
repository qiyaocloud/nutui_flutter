// NutUI 风格图标组件
class NutIcon extends StatelessWidget {
  // 图标数据
  final IconData icon;

  // 图标大小
  final double size;

  // 图标颜色
  final Color? color;

  // 点击回调 (如果设置了此属性，会自动包裹点击区域)
  final VoidCallback? onTap;

  // 点击时的水波纹颜色 (默认透明，即无水波纹，只有点击缩放反馈)
  final Color? splashColor;

  const NutIcon({
    super.key,
    required this.icon,
    this.size = 20,
    this.color,
    this.onTap,
    this.splashColor = Colors.transparent,
  });

  @override
  Widget build(BuildContext context) {
    // 获取默认颜色 (尊重 IconTheme 主题)
    final IconThemeData iconTheme = IconTheme.of(context);
    final Color effectiveColor = color ?? iconTheme.color ?? NutUIColors.text;

    // 构建Icon
    Widget result = Icon(
      icon,
      size: size,
      color: effectiveColor,
    );

    // 如果没有点击事件，直接返回
    if (onTap == null) {
      return result;
    }

    // 如果有点击事件，包装手势和点击区域
    // 解决原生 IconButton 默认 48px 内边距过大的痛点
    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      child: _buildClickableWrapper(result),
    );
  }

  // 构建可点击的包装器 (带微动效)
  Widget _buildClickableWrapper(Widget child) {
    // 使用 InkWell 实现水波纹 (默认配置为透明水波，仅保持微动效)
    return InkWell(
      onTap: onTap,
      splashColor: splashColor,
      highlightColor: splashColor?.withValues(alpha: 0.1) ?? Colors.transparent, // 点击高亮色
      borderRadius: BorderRadius.circular(size / 2), // 让水波纹呈圆形
      child: ConstrainedBox(
        constraints: BoxConstraints(minWidth: size + 8, minHeight: size + 8), // 稍微扩大点击热区
        child: Center(child: child),
      ),
    );
  }
}
